#!/bin/sh
# One makefile for every configuration of a MPLAB X project, and a driver.
# usage: genmakefile-mplabx-all.sh PROJECT.X OUTDIR [genmakefile options]
# writes OUTDIR/Makefile.<configuration> for each <conf name="..."> of
# PROJECT.X/nbproject/configurations.xml, and OUTDIR/Makefile that builds them
# all ("make"), or one ("make <configuration>"), or cleans them ("make clean").
[ $# -ge 2 ] || { echo "usage: $0 PROJECT.X OUTDIR [genmakefile options]" >&2; exit 1; }
proj=$1 out=$2
shift 2
G=${GENMAKEFILE:-genmakefile}
mkdir -p "$out" || exit 1
out=$(cd "$out" && pwd) || exit 1
cd "$proj" || exit 1
status=0
confs=
for conf in $(sed -n 's/^ *<conf name="\([^"]*\)".*/\1/p' nbproject/configurations.xml); do
  if "$G" --import-mplabx nbproject/configurations.xml --mplabx-conf "$conf" "$@" -o "$out/Makefile.$conf"; then
    confs="$confs $conf"
  else
    status=1
  fi
done
{
  echo "# Generated by genmakefile-mplabx-all.sh: one makefile for each configuration"
  echo "CONFIGURATIONS =$confs"
  echo
  echo ".PHONY: all clean \$(CONFIGURATIONS)"
  echo "all: \$(CONFIGURATIONS)"
  echo
  echo "\$(CONFIGURATIONS):"
  printf '\t$(MAKE) -f Makefile.$@\n'
  echo
  echo "clean:"
  printf '\t@for c in $(CONFIGURATIONS); do $(MAKE) -f Makefile.$$c clean; done\n'
} >"$out/Makefile"
exit $status
